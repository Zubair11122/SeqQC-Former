#!/usr/bin/env python3
"""
19_evaluate_predictions_ci_thresholds.py

Create publication-ready threshold tables and bootstrap confidence intervals
from a prediction CSV generated by 18_train_reviewer_safe.py.

Input CSV must contain:
  y_true, probability

Outputs:
  - threshold_metrics.csv
  - bootstrap_confidence_intervals.csv
  - metrics_summary.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)


def metrics(y, p, threshold):
    pred = (p >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    return {
        "threshold": float(threshold),
        "auroc": float(roc_auc_score(y, p)) if len(np.unique(y)) == 2 else np.nan,
        "auprc": float(average_precision_score(y, p)) if len(np.unique(y)) == 2 else np.nan,
        "accuracy": float(accuracy_score(y, pred)),
        "precision": float(precision_score(y, pred, zero_division=0)),
        "recall": float(recall_score(y, pred, zero_division=0)),
        "f1": float(f1_score(y, pred, zero_division=0)),
        "tp": int(tp), "tn": int(tn), "fp": int(fp), "fn": int(fn),
    }


def bootstrap_ci(y, p, threshold, n_boot=1000, seed=42):
    rng = np.random.default_rng(seed)
    rows = []
    n = len(y)
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        yb = y[idx]
        pb = p[idx]
        if len(np.unique(yb)) < 2:
            continue
        rows.append(metrics(yb, pb, threshold))
    boot = pd.DataFrame(rows)
    ci_rows = []
    for col in ["auroc", "auprc", "accuracy", "precision", "recall", "f1"]:
        vals = boot[col].dropna().values
        ci_rows.append({
            "metric": col,
            "estimate": metrics(y, p, threshold)[col],
            "ci_lower_95": float(np.percentile(vals, 2.5)),
            "ci_upper_95": float(np.percentile(vals, 97.5)),
            "n_bootstrap_used": int(len(vals)),
        })
    return pd.DataFrame(ci_rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--predictions", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--thresholds", default="0.50,0.75,0.90")
    ap.add_argument("--primary-threshold", type=float, default=None)
    ap.add_argument("--n-bootstrap", type=int, default=1000)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    pred_path = Path(args.predictions)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    df = pd.read_csv(pred_path)
    if not {"y_true", "probability"}.issubset(df.columns):
        raise KeyError("Prediction CSV must contain y_true and probability columns")

    y = df["y_true"].astype(int).values
    p = df["probability"].astype(float).values
    thresholds = [float(x.strip()) for x in args.thresholds.split(",") if x.strip()]
    primary = args.primary_threshold if args.primary_threshold is not None else thresholds[0]

    thr_table = pd.DataFrame([metrics(y, p, t) for t in thresholds])
    thr_table.to_csv(out_dir / "threshold_metrics.csv", index=False)

    ci = bootstrap_ci(y, p, primary, n_boot=args.n_bootstrap, seed=args.seed)
    ci.to_csv(out_dir / "bootstrap_confidence_intervals.csv", index=False)

    summary = {
        "prediction_file": str(pred_path),
        "n": int(len(y)),
        "n_positive": int(y.sum()),
        "positive_fraction": float(y.mean()),
        "primary_threshold": float(primary),
        "primary_metrics": metrics(y, p, primary),
    }
    with open(out_dir / "metrics_summary.json", "w") as f:
        json.dump(summary, f, indent=2)

    print("✅ Evaluation tables written")
    print(f"Output directory: {out_dir.resolve()}")
    print(thr_table.to_string(index=False))
    print("\n95% bootstrap CI:")
    print(ci.to_string(index=False))


if __name__ == "__main__":
    main()
